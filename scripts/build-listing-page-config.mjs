#!/usr/bin/env node
/**
 * Writes docs/listing-config.js for the public listing page (docs/listing.html, GitHub Pages)
 * from EXPO_PUBLIC_SUPABASE_URL / EXPO_PUBLIC_SUPABASE_ANON_KEY in .env.
 *
 * The anon key is designed to be public (it already ships inside the app); row-level security
 * decides what it can read. Never put the service-role key here.
 *
 *   node scripts/build-listing-page-config.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const env = Object.fromEntries(
  fs
    .readFileSync(path.join(root, '.env'), 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#') && line.includes('='))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^['"]|['"]$/g, '')];
    }),
);

const url = env.EXPO_PUBLIC_SUPABASE_URL;
const anonKey = env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !anonKey) {
  console.error('Missing EXPO_PUBLIC_SUPABASE_URL or EXPO_PUBLIC_SUPABASE_ANON_KEY in .env');
  process.exit(1);
}
if (/service_role/.test(Buffer.from(anonKey.split('.')[1] ?? '', 'base64').toString('utf8'))) {
  console.error('Refusing to publish a service_role key. Use the anon key.');
  process.exit(1);
}

const out = `// Generated by scripts/build-listing-page-config.mjs — public Supabase anon config.
window.REYELTOR_CONFIG = ${JSON.stringify(
  {
    supabaseUrl: url,
    supabaseAnonKey: anonKey,
    storageBucket: 'reyeltor-listings',
    appScheme: 'reyeltor',
    playStoreUrl: 'https://play.google.com/store/apps/details?id=uz.reyeltor.app',
  },
  null,
  2,
)};
`;
fs.writeFileSync(path.join(root, 'docs/listing-config.js'), out);
console.log('Wrote docs/listing-config.js');
